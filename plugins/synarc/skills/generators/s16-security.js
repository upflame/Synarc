module.exports = {
  generateS16(w) {
    w('## S16 — SECURITY PATTERNS');
    w('');
    w('Security patterns are mandatory checks applied to every interaction that touches authentication, authorization, data handling, network configuration, secrets management, or input/output processing. These patterns enforce security best practices as deterministic gates, not recommendations.');
    w('');
    w('### Authentication Patterns');
    w('');
    w('- All authentication tokens must have explicit expiration (exp claim in JWT)');
    w('- Token validation must include: expiration, issuer, audience, signature');
    w('- Session tokens must be revocable (token blocklist or short TTL)');
    w('- Password storage must use a key-derivation function (bcrypt, argon2, scrypt)');
    w('- MFA should use TOTP or WebAuthn, never SMS-only');
    w('- API keys must be rotatable and scoped to minimum required permissions');
    w('- OAuth2 flows must use PKCE for public clients');
    w('- Cross-service authentication must use mTLS or signed tokens, not shared secrets');
    w('');
    w('### Authorization Patterns');
    w('');
    w('- Authorization check must happen on every request, not cached from previous check');
    w('- Default access is DENY — explicitly allow, never explicitly deny then fall through to allow');
    w('- Role-based access control (RBAC) with principle of least privilege');
    w('- Authorization logic must be in middleware, not scattered in route handlers');
    w('- Admin endpoints must have separate, stricter authorization');
    w('- Rate limiting must be per-user, per-endpoint, and per-IP');
    w('');
    w('### Input Validation Patterns');
    w('');
    w('- All input must be validated against a schema (never trust client-provided data)');
    w('- SQL: use parameterized queries or ORM — never concatenate user input into SQL');
    w('- NoSQL: use query builders with type checking — avoid raw query strings');
    w('- File uploads: validate type, size, content; store outside web root; serve through download handler');
    w('- URLs: validate against allowlist, not blocklist');
    w('- Serialization: use safe deserialization libraries — never eval or unsafe deserialization');
    w('- Command injection: never pass user input to shell commands; use language-native APIs');
    w('');
    w('### Data Protection Patterns');
    w('');
    w('- PII must be encrypted at rest and in transit');
    w('- Secrets must be stored in a secrets manager, not in code, config files, or environment variables');
    w('- Logs must never contain passwords, tokens, PII, or full credit card numbers');
    w('- Data in transit must use TLS 1.2+ with strong cipher suites');
    w('- Database credentials must be rotated regularly');
    w('- Backups must be encrypted');
    w('');
    w('### Output Encoding Patterns');
    w('');
    w('- HTML output: encode for context (HTML entity, attribute, URL, JavaScript)');
    w('- API responses: use structured types, never serialized user input directly');
    w('- Error messages: return generic messages to users, detailed messages to logs');
    w('- Redirect URLs: validate against allowlist');
    w('- Content-Type headers: set explicitly, never derive from user input');
    w('');
    w('### Dependency Security Patterns');
    w('');
    w('- Use package lockfiles (package-lock.json, yarn.lock, poetry.lock, go.sum)');
    w('- Run dependency vulnerability scanning (npm audit, pip-audit, snyk, trivy)');
    w('- Pin dependency versions in production (no ^ or ~ ranges)');
    w('- Monitor CVEs for all dependencies');
    w('- Have a dependency update policy (patch = 7 days, minor = 30 days, major = 90 days)');
    w('');
    w('### Network Security Patterns');
    w('');
    w('- All internal services should communicate over mTLS');
    w('- Network segmentation: DMZ, application tier, data tier — no direct data tier access from outside');
    w('- Egress filtering: only allow outbound traffic to known, required endpoints');
    w('- Ingress filtering: deny all by default, allow only necessary ports and protocols');
    w('- DNS: use encrypted DNS (DoH/DoT) for outbound; internal DNS for service discovery');
    w('');
    w('### Logging and Monitoring Security');
    w('');
    w('- Log all authentication attempts (success and failure)');
    w('- Log all authorization failures');
    w('- Log all data access to sensitive resources');
    w('- Alert on: brute force attempts, unusual access patterns, permission escalations');
    w('- Audit logs must be append-only and immutable');
    w('');
    w('Load references/security-patterns.md for the complete security pattern library including OWASP Top 10 coverage, threat modeling templates (STRIDE-M), compliance requirements (SOC2, HIPAA, PCI-DSS, GDPR), and security testing procedures.');
    w('');
  }
};
